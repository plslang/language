// compiler/codegen.cpp - banner, includes, globals, forward decls, bodies
#include "compiler.hpp"

using namespace std;

extern const char* PL_VERSION;
extern const char* PL_LANG_VERSION;

string emitBanner(const string& srcName) {
    ostringstream out;
    out << "// generated by pl from " << srcName << "\n";
    out << "// date-iso: " << isoDateNow() << "\n";
    out << "// language: " << PL_LANG_VERSION << "\n";
    out << "// compiler: pl " << PL_VERSION << "\n";
    out << "\n";
    return out.str();
}

string emitIncludes(bool usesMath) {
    ostringstream out;
    out << "// library for print\n";
    out << "#include <iostream>\n";
    out << "// library for exit codes\n";
    out << "#include <cstdlib>\n";
    out << "// library for strings\n";
    out << "#include <string>\n";
    if (usesMath) {
        out << "// library for math (using math)\n";
        out << "#include <cmath>\n";
    }
    out << "using namespace std;\n";
    out << "\n";

    // [CONCAT] хелпер для "string + bool"
    out << "// helper for string + bool concatenation\n";
    out << "static inline string __pla_bool_to_str(bool b) {\n";
    out << "    return b ? \"true\" : \"false\";\n";
    out << "}\n";
    out << "\n";

    return out.str();
}

string emitGlobals(const map<string, GlobalInfo>& globals) {
    ostringstream out;
    if (globals.empty()) return "";

    out << "// global variables\n";
    for (const auto& kv : globals) {
        const string& name = kv.first;
        const GlobalInfo& gi = kv.second;
        out << "// global " << gi.type << " " << name << " (declared in "
            << gi.declaredIn << ")\n";

        string init;
        if (gi.init) {
            if (gi.init->kind == Expr::NUM) {
                init = to_string(gi.init->numValue);
            } else if (gi.init->kind == Expr::STR) {
                init = cppStringLiteral(gi.init->strValue);
            } else {
                init = defaultFor(gi.type);
            }
        } else {
            init = defaultFor(gi.type);
        }

        out << "static " << typeFor(gi.type) << " "
            << cppGlobalIdent(name) << " = " << init << ";\n";
    }
    out << "\n";
    return out.str();
}

string emitForwardDeclarations(const Program& prog,
                               const map<string, FuncInfo>& funcs)
{
    ostringstream out;
    out << "// forward declarations\n";
    for (const auto& f : prog.functions) {
        const auto& fi = funcs.at(f.name);
        out << cppRetType(fi.retType) << " fn_" << f.name << "(";
        for (size_t i = 0; i < fi.declares.size(); ++i) {
            if (i) out << ", ";
            out << typeFor(fi.declares[i].type) << "& "
                << cppIdentFor(f.name, fi.declares[i].name);
        }
        out << ");\n";
    }
    out << "\n";
    return out.str();
}

// ---------- statement block emitter ----------
string emitStmtBlock(const vector<Stmt>& body,
                     const string& fn,
                     const FuncScope& sc,
                     const map<string, GlobalInfo>& globals,
                     const map<string, FuncInfo>& funcs,
                     int indent,
                     FuncRet currentRet)
{
    ostringstream out;
    string p(indent * 4, ' ');

    for (const auto& s : body) {
        switch (s.kind) {
            case Stmt::PRINT:
                out << p << emitPrint(s, fn, sc, globals, funcs);
                break;
            case Stmt::EXIT:
                out << p << emitExit(s);
                break;
            case Stmt::CALL:
                out << p << emitCall(s, fn, sc, globals, funcs);
                break;
            case Stmt::DECL:
                out << p << emitDecl(s, fn, sc, globals, funcs);
                break;
            case Stmt::ASSIGN:
                out << p << emitAssign(s, fn, sc, globals, funcs);
                break;
            case Stmt::DECLARE:
                out << p << emitDeclare(s, fn);
                break;
            case Stmt::GLOBAL:
                out << p << emitGlobalMarker(s);
                break;
            case Stmt::USING:
                break;
            case Stmt::CIN:
                out << p << emitCin(s, fn, sc, globals);
                break;
            case Stmt::IF:
                out << emitIf(s, fn, sc, globals, funcs, indent);
                break;
            case Stmt::WHILE:
                out << emitWhile(s, fn, sc, globals, funcs, indent);
                break;
            case Stmt::PASS:
                out << p << emitPass(s);
                break;
            case Stmt::CONTINUE:
                out << p << emitContinue(s);
                break;
            case Stmt::RETURN:
                out << p << emitReturn(s, fn, sc, globals, funcs, currentRet);
                break;
            case Stmt::DIRECTIVE:
                break;
        }
    }
    return out.str();
}

string emitFunction(const Function& f,
                    const FuncScope& sc,
                    const map<string, GlobalInfo>& globals,
                    const map<string, FuncInfo>& funcs)
{
    ostringstream out;

    const auto& fi = funcs.at(f.name);

    out << "// code - " << f.name << ":\n";
    out << cppRetType(fi.retType) << " fn_" << f.name << "(";
    for (size_t i = 0; i < fi.declares.size(); ++i) {
        if (i) out << ", ";
        out << typeFor(fi.declares[i].type) << "& "
            << cppIdentFor(f.name, fi.declares[i].name);
    }
    out << ") {\n";

    out << emitStmtBlock(f.body, f.name, sc, globals, funcs, 1, fi.retType);

    out << "}\n\n";
    return out.str();
}