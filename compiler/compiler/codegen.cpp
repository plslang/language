// compiler/codegen.cpp - emit banner, includes, forward decls, function bodies
#include <string>
#include <vector>
#include <sstream>
#include <map>
#include <set>
#include <memory>

using namespace std;

extern const char* PL_VERSION;
extern const char* PL_LANG_VERSION;

string isoDateNow();

struct Expr {
    enum Kind { NUM, STR, VAR, BINOP } kind;
    long long numValue = 0;
    string strValue;
    string varName;
    char op = 0;
    shared_ptr<Expr> lhs;
    shared_ptr<Expr> rhs;
    int line = 0;
};
using ExprPtr = shared_ptr<Expr>;

struct Stmt {
    enum Kind { PRINT, EXIT, CALL, DECL, ASSIGN, DECLARE, GLOBAL, USING } kind;
    bool newline = false;
    ExprPtr printExpr;
    int exitCode = 0;
    string callName;
    string varType;
    string varName;
    ExprPtr varInit;
    string usingModule;
    int line = 0;
};

struct Function {
    string name;
    vector<Stmt> body;
};

struct Program {
    vector<Function> functions;
    int mainIndex = -1;
    bool usesMath = false;
};

struct GlobalInfo {
    string type;
    ExprPtr init;      // NUM / STR / VAR
    string declaredIn;
    int    line = 0;
};

struct FuncScope {
    map<string,string> vars;
    map<string,string> declareTypes;
    set<string>        declares;
};

struct DeclareInfo {
    string type;
    string name;
};

// ---------- cross-module prototypes ----------
string cppStringLiteral(const string& s);
string cppIdentFor(const string& fn, const string& var);
string cppGlobalIdent(const string& name);
string typeFor(const string& t);
bool   isNumericLiteral(const string& s);

string renderExpr(const ExprPtr& e, const string& fn, const FuncScope& sc,
                  const map<string, GlobalInfo>& globals);
string renderLValue(const string& fn, const FuncScope& sc,
                    const map<string, GlobalInfo>& globals, const string& name);

string emitPrint(const Stmt& s, const string& fn, const FuncScope& sc,
                 const map<string, GlobalInfo>& globals);
string emitExit(const Stmt& s);
string emitCall(const Stmt& s, const string& fn, const FuncScope& sc,
                const map<string, GlobalInfo>& globals,
                const map<string, vector<DeclareInfo>>& declares);
string emitDecl(const Stmt& s, const string& fn, const FuncScope& sc,
                const map<string, GlobalInfo>& globals);
string emitAssign(const Stmt& s, const string& fn, const FuncScope& sc,
                  const map<string, GlobalInfo>& globals);
string emitDeclare(const Stmt& s, const string& fn);
string emitGlobalMarker(const Stmt& s);

// ---------- banner / includes ----------
string emitBanner(const string& srcName) {
    ostringstream out;
    out << "// generated by pl from " << srcName << "\n";
    out << "// date-iso: " << isoDateNow() << "\n";
    out << "// language: " << PL_LANG_VERSION << "\n";
    out << "// compiler: pl " << PL_VERSION << "\n";
    out << "\n";
    return out.str();
}

string emitIncludes(bool usesMath) {
    ostringstream out;
    out << "// library for print\n";
    out << "#include <iostream>\n";
    out << "// library for exit codes\n";
    out << "#include <cstdlib>\n";
    out << "// library for strings\n";
    out << "#include <string>\n";
    if (usesMath) {
        out << "// library for math (using math)\n";
        out << "#include <cmath>\n";
    }
    out << "using namespace std;\n";
    out << "\n";
    return out.str();
}

// ---------- globals ----------
string emitGlobals(const map<string, GlobalInfo>& globals) {
    ostringstream out;
    if (globals.empty()) return "";

    out << "// global variables\n";
    for (const auto& kv : globals) {
        const string& name = kv.first;
        const GlobalInfo& gi = kv.second;
        out << "// global " << gi.type << " " << name << " (declared in "
            << gi.declaredIn << ")\n";

        string init;
        if (gi.init) {
            if (gi.init->kind == Expr::NUM) {
                init = to_string(gi.init->numValue);
            } else if (gi.init->kind == Expr::STR) {
                init = cppStringLiteral(gi.init->strValue);
            } else {
                init = (gi.type == "int") ? "0" : "\"\"";
            }
        } else {
            init = (gi.type == "int") ? "0" : "\"\"";
        }

        if (gi.type == "int") {
            out << "static long long " << cppGlobalIdent(name)
                << " = " << init << ";\n";
        } else {
            out << "static std::string " << cppGlobalIdent(name)
                << " = " << init << ";\n";
        }
    }
    out << "\n";
    return out.str();
}

// ---------- forward declarations ----------
string emitForwardDeclarations(const Program& prog,
                               const map<string, vector<DeclareInfo>>& declares)
{
    ostringstream out;
    out << "// forward declarations\n";
    for (const auto& f : prog.functions) {
        out << "void fn_" << f.name << "(";
        const auto& ds = declares.at(f.name);
        for (size_t i = 0; i < ds.size(); ++i) {
            if (i) out << ", ";
            out << typeFor(ds[i].type) << "& " << cppIdentFor(f.name, ds[i].name);
        }
        out << ");\n";
    }
    out << "\n";
    return out.str();
}

// ---------- function body ----------
string emitFunction(const Function& f,
                    const FuncScope& sc,
                    const map<string, GlobalInfo>& globals,
                    const map<string, vector<DeclareInfo>>& declares)
{
    ostringstream out;

    out << "// code - " << f.name << ":\n";
    out << "void fn_" << f.name << "(";
    const auto& ds = declares.at(f.name);
    for (size_t i = 0; i < ds.size(); ++i) {
        if (i) out << ", ";
        out << typeFor(ds[i].type) << "& " << cppIdentFor(f.name, ds[i].name);
    }
    out << ") {\n";

    for (const auto& s : f.body) {
        switch (s.kind) {
            case Stmt::PRINT:   out << emitPrint(s, f.name, sc, globals); break;
            case Stmt::EXIT:    out << emitExit(s); break;
            case Stmt::CALL:    out << emitCall(s, f.name, sc, globals, declares); break;
            case Stmt::DECL:    out << emitDecl(s, f.name, sc, globals); break;
            case Stmt::ASSIGN:  out << emitAssign(s, f.name, sc, globals); break;
            case Stmt::DECLARE: out << emitDeclare(s, f.name); break;
            case Stmt::GLOBAL:  out << emitGlobalMarker(s); break;
            case Stmt::USING:   /* already handled in parseProgram */ break;
        }
    }

    out << "}\n\n";
    return out.str();
}